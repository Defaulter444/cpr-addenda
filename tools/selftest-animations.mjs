import assert from 'node:assert/strict';
import {WEAPON_EFFECTS, FREE_WEAPON_EFFECTS, resolveWeaponEffect, weaponAnimationProfile as profile, areaAnimationEffect, animationRecipients, isAnimatedWeaponRoll} from '../scripts/weapon-animation-profiles.js';
import {registerWeaponAnimations} from '../scripts/weapon-animations.js';
let checks=0;
const eq=(a,b,label)=>{assert.deepEqual(a,b,label);checks++;};
const item=(type,name='Моё оружие',more={})=>({type:'weapon',name,system:{weaponType:type,...more}});
for(const [key,path] of Object.entries(WEAPON_EFFECTS)) {
  eq(resolveWeaponEffect(key,()=>true),path,'Prefer installed Patreon variant: '+key);
  const free=FREE_WEAPON_EFFECTS[key]??path;
  eq(resolveWeaponEffect(key,p=>p===free),free,'Free-only library: '+key);
  eq(resolveWeaponEffect(key,()=>false),null,'Missing asset: '+key);
}
eq(resolveWeaponEffect('unknown',()=>true),null,'Unknown profile cannot select an arbitrary asset');
for(const type of ['assaultRifle','heavyPistol','heavySmg','medPistol','rocketLauncher','shotgun','smg','sniperRifle','vHeavyPistol','bow','thrownWeapon','lightMelee','medMelee','heavyMelee','vHeavyMelee','unarmed','martialArts','grenadeLauncher']) eq(Boolean(profile(item(type))),true,type);
eq(profile({type:'gear',name:'Пистолет',system:{}}),null,'No animation for descriptive gear');
eq(profile(item('shotgun')).effect,'bullet','Slugs are individual shots');
eq(profile(item('bow','Арбалет')).effect,'bolt','Crossbow');
eq(profile(item('heavyMelee','Молот')).effect,'blunt','Blunt appearance');
eq(profile(item('shotgun','Огнемёт')).effect,'flame','Flame');
eq(profile({type:'cyberware',name:'Когти',system:{isWeapon:true}}).effect,'claws','Cyberweapon');
eq(profile({type:'cyberware',name:'Когти',system:{isWeapon:false}}),null,'Cosmetic implant');
for(const [type,effect] of Object.entries({emp:'shock',flashbang:'flash',smoke:'smoke',poison:'smoke',teargas:'smoke',acid:'flash',basic:'explosion'})) eq(areaAnimationEffect({kind:'blast',profile:{type}}),effect,type);
eq(areaAnimationEffect({kind:'shot',profile:{type:'basic'}}),'bullet','Shotgun fan');
eq(animationRecipients({whisper:[],user:{id:'player'}}),null,'Public');
eq(animationRecipients({whisper:['gm'],user:{id:'player'}}),['gm','player'],'GM roll visible to author');
eq(animationRecipients({whisper:['gm'],user:{id:'player'},blind:true}),['gm'],'Blind roll hidden from author');
eq(animationRecipients({whisper:[{id:'player'}],user:{id:'player'}}),['player'],'Self roll');
for(const type of ['attack','aimed-attack','autofire','suppressive-fire']) eq(isAnimatedWeaponRoll({rollCard:`systems/cyberpunk-red-core/templates/chat/cpr-${type}-rollcard.hbs`}),true,type);
for(const type of ['damage','skill','deathsave','net-attack']) eq(isAnimatedWeaponRoll({rollCard:`systems/cyberpunk-red-core/templates/chat/cpr-${type}-rollcard.hbs`}),false,type);
const callbacks=new Map(),settings=new Map();
globalThis.game={settings:{register:(namespace,key,value)=>settings.set(key,value),get:()=>true}};
globalThis.Hooks={once:()=>{},on:(name,callback)=>callbacks.set(name,callback)};
registerWeaponAnimations();
eq(settings.get('weaponAnimations').default,false,'Other worlds opt in explicitly');
const workflow=callbacks.get('AutomatedAnimations-WorkflowStart');
const native={item:item('heavyPistol')};workflow(native,{customized:true});
eq(native.stopWorkflow,true,'Native AA chat listener cannot duplicate our post-roll dispatch');
const custom={item:item('heavyPistol'),addendaWeaponAnimation:{}};workflow(custom,{customized:true});
eq(custom.stopWorkflow,undefined,'Explicit custom AA animation retains control');
const disabled={item:{...item('heavyPistol'),flags:{autoanimations:{isEnabled:false}}},addendaWeaponAnimation:{}};workflow(disabled,null);
eq(disabled.stopWorkflow,true,'Disabled item cannot receive fallback');
const unrelated={item:{type:'gear',name:'Пистолет',system:{}}};workflow(unrelated,{customized:true});
eq(unrelated.stopWorkflow,undefined,'Unrelated item animations are untouched');
console.log(JSON.stringify({pass:true,checks}));
