def cyberware(doc_id, name, kind, price, humanity_roll, humanity_static,
              description, foundational=False, slots=0, effects=None):
    """Киберимплант в том виде, в каком его ждёт система.

    @param {str} doc_id - идентификатор, 16 символов
    @param {str} name - название по Data Pool
    @param {str} kind - подтип: borgware, cyberwareExternal и т.д.
    @param {int} price - цена в еддиках
    @param {str} humanity_roll - бросок потери человечности, например "4d6"
    @param {int} humanity_static - её среднее значение
    @param {str} description - описание, дословно из документа
    @param {bool} foundational - основной ли имплант
    @param {int} slots - сколько всего в него ставится
    @param {list} effects - активные эффекты
    """
    return {
        "_id": doc_id,
        "name": name,
        "type": "cyberware",
        "img": BORG_ICON,
        "folder": None,
        "sort": 0,
        "effects": effects or [],
        "flags": {},
        "system": {
            "ammoVariety": [],
            "attackmod": 0,
            "brand": "",
            "canIgnoreArmor": False,
            "concealable": {"concealable": False, "isConcealed": False},
            "core": False,
            "critFailEffect": "jammed",
            "damage": "1d6",
            "description": {"value": description},
            "dvTable": "",
            "favorite": False,
            "fireModes": {"autoFire": 0, "suppressiveFire": False},
            "humanityLoss": {"roll": humanity_roll, "static": humanity_static},
            "ignoreArmorPercent": 0,
            "ignoreBelowSP": 0,
            "installLocation": "hospital",
            "installedItems": {
                "allowed": slots > 0,
                "allowedTypes": ["itemUpgrade", "cyberware"],
                "list": [],
                "slots": slots,
                "usedSlots": 0,
            },
            "isElectronic": True,
            "isFoundational": foundational,
            "isRanged": False,
            "isWeapon": False,
            "magazine": {"ammoData": None, "max": 0, "value": 0},
            "price": {"market": price},
            "providesHardening": False,
            "revealed": True,
            "rof": 1,
            "size": 1,
            "source": dict(SOURCE_REF),
            "type": kind,
            "unarmedAutomaticCalculation": True,
            "usage": "installed",
            "usesType": "magazine",
            "weaponSkill": "",
            "weaponType": "",
        },
    }


def armor(doc_id, name, sp, penalty, description):
    """Парный предмет брони: он и держит ОС, который считает система.

    Голова и тело одним предметом: документ даёт одно значение «для тела и
    головы», а не два разных, и разносить его на две записи значило бы
    заставить мастера надевать обе и следить за их износом порознь.

    @param {str} doc_id - идентификатор, 16 символов
    @param {str} name - название с пометкой «(броня)»
    @param {int} sp - ОС
    @param {int} penalty - штраф брони, отрицательным числом
    @param {str} description - откуда эта броня взялась
    """
    return {
        "_id": doc_id,
        "name": name,
        "type": "armor",
        "img": ARMOR_ICON,
        "folder": None,
        "sort": 0,
        "effects": [],
        "flags": {},
        "system": {
            "bodyLocation": {"ablation": 0, "sp": sp},
            "brand": "",
            "concealable": {"concealable": False, "isConcealed": False},
            "description": {"value": description},
            # Броня приезжает надетой: имплант с неё не снимешь, а
            # ненадетая она не считается системой вовсе.
            "equipped": "equipped",
            "favorite": False,
            "headLocation": {"ablation": 0, "sp": sp},
            "installedItems": {
                "allowed": False,
                "allowedTypes": ["itemUpgrade"],
                "list": [],
                "slots": 0,
                "usedSlots": 0,
            },
            "isBodyLocation": True,
            "isElectronic": False,
            "isHeadLocation": True,
            "isShield": False,
            # Система берёт штраф по модулю, но в модуле он всюду записан
            # со знаком минус — так его видно как штраф, а не как бонус.
            "penalty": penalty,
            "price": {"market": 0},
            "providesHardening": False,
            "revealed": True,
            "shieldHitPoints": {"max": 0, "value": 0},
            "source": dict(SOURCE_REF),
            "usage": "equipped",
        },
    }


