"""
Боргирование из Data Pool: то, чего нет в системе.

Со страницы «Экзоскелеты/Боргирование» семнадцать позиций. Двенадцать система
уже везёт своими компендиумами — их этот скрипт не трогает. Остаются пять, и
все они из ПНМ: «БИОСИСТЕМА», две «Брони Драгуна», «Тяжёлая Подкожная Броня» и
«Эндоскелет Ω».

Три из них дают ОС. В Cyberpunk RED киберимплант сам броню не считает — система
и в своих предметах пишет об этом прямо: у «Вплетения в плоть» и «Подкожной
брони» есть парный предмет типа armor, а в описании импланта стоит просьба
добавить его на лист. Повторяем ровно этот приём: имплант с ПЧ и ценой плюс
предмет брони с ОС и штрафом. Иначе получилось бы как с силовой бронёй, где ОС
стоял в шапке и не вычитался (см. 0.12.0).

«Эндоскелет Ω» этот скрипт не трогает: его файл собирает build_pkt_implants по
docs/implant-map.json, где и лежат числа Data Pool. Двое пишущих в один файл —
это стёртая правка при следующей сборке, что однажды уже случилось.

    python tools/import_borgware.py
    node tools/build-packs.js
"""

