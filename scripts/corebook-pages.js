/**
 * Номера страниц: из английской книги в русскую.
 *
 * У предметов системы источник записан по **английскому** изданию: «Core, 341».
 * Русское издание переведено постранично, и почти вся книга совпадает с
 * английской один в один — но не каталог. В главе «Новая экономика улиц»
 * («Приложение к ночному рынку») вёрстка разъезжается: русские таблицы то
 * длиннее, то компактнее английских, и разделы съезжают на пять-шесть страниц.
 *
 * Поэтому ссылка «Core, стр. 341» — таблица дальнобойного оружия — открывала
 * русскую 341, где идут «специалисты» и рассуждение про постапокалипсис.
 *
 * Общим смещением это не лечится, и даже отрезками с постоянным сдвигом — тоже:
 * сдвиг гуляет внутри каталога. Русские боеприпасы занимают две страницы там,
 * где английские три, а снаряжение — наоборот, пять вместо четырёх. Поэтому
 * здесь таблица по страницам.
 *
 * ОТКУДА ЧИСЛА. Главный источник — указатель, напечатанный в самой книге на
 * русской странице 346. Он прямо говорит, где начинается каждый раздел каталога:
 *
 *   Холодное оружие 346, Дальнобойное 347, Качества оружия 348,
 *   Приспособления 349, Боеприпасы 351, Экзотическое оружие 353,
 *   Броня 356, Общее снаряжение 357, Мода 362, Уличные наркотики 363,
 *   Киберимпланты 364, Железо для кибердеки 371, Программы 372
 *
 * Указателю можно верить буквально: разделы в нём отмечены по заголовку, а
 * заголовок нередко стоит внизу страницы. «Железо для кибердеки» действительно
 * начинается на 371 — под таблицей боргирования, — хотя первую половину той же
 * страницы занимают опции киберконечностей. Программы так же начинаются внизу
 * 372, а их таблица разворачивается на 373.
 *
 * Английские границы тех же разделов взяты из самой системы: у каждого предмета
 * записана его английская страница, и по ним видно, где раздел начинается и
 * кончается. Страницы внутри раздела разложены измерением —
 * `tools/measure_corebook_pages.py` ищет русские названия предметов в тексте
 * PDF и берёт медиану по однозначным находкам.
 *
 * Каждая строка таблицы проверена отдельно по тексту книги.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Точности до предмета. Внутри раздела записи идут по алфавиту,
 * а алфавит у языков разный: «Malorian Arms 3516» и «Микроволновка» стоят в
 * своих книгах в разном порядке. Поэтому ссылка ведёт в нужный раздел и на
 * нужный разворот, но конкретная запись может оказаться страницей дальше. Точнее
 * без ручной разметки каждой позиции не сделать, а такая разметка живёт ровно до
 * следующего переиздания.
 */

/** Издание книги, для которого посчитана таблица. */
export const BOOK_EDITION = "ru-v13";

/** Последняя напечатанная страница русского издания. */
export const LAST_PAGE = 457;

/** Первая и последняя страницы каталога по английскому изданию. */
const CATALOGUE_FIRST = 340;
const CATALOGUE_LAST = 370;

/**
 * Каталог: английская страница -> русская.
 *
 * Разрывы в правом столбце не опечатки. Там, где русский текст компактнее, две
 * английские страницы ложатся на одну русскую (347 и 348 обе ведут на 353);
 * там, где длиннее, номер перескакивает (353 сразу за 355).
 */
export const PAGE_MAP = {
  340: 346, // холодное оружие
  341: 347, // дальнобойное оружие
  342: 348, // качества оружия и примеры брендов
  343: 349, // приспособления для оружия
  344: 350, // приспособления, продолжение
  345: 351, // боеприпасы
  346: 352, // боеприпасы, продолжение
  347: 353, // боеприпасы кончаются и начинается экзотическое оружие
  348: 353, // экзотическое оружие
  349: 355, // экзотическое оружие, продолжение
  350: 356, // броня
  351: 357, // броня, окончание
  352: 358, // общее снаряжение
  353: 359, // снаряжение, продолжение
  354: 360, // снаряжение, продолжение
  355: 360, // снаряжение, окончание
  356: 362, // мода
  357: 363, // уличные наркотики
  358: 364, // киберимпланты: стилевые
  359: 365, // нейроимпланты
  360: 366, // кибероптика
  361: 367, // кибераудио
  362: 367, // кибераудио, продолжение
  363: 368, // внутренние импланты
  364: 369, // киберконечности
  365: 370, // опции киберруки
  366: 371, // опции киберноги
  367: 371, // покрытия, крепления, эндоскелеты
  368: 371, // железо для кибердеки (начинается внизу этой страницы)
  369: 373, // атакующие программы
  370: 374, // программы «чёрный лёд»
};

/**
 * Насколько русская книга опережает английскую за каталогом.
 *
 * За 370-й страницей мерить нечем: это самая дальняя страница-источник во всей
 * системе. Но обрывать поправку там нельзя — вышло бы, что ссылка на 370 ведёт
 * вперёд, на 374, а на 371 назад, на 371. Поэтому дальше держится последний
 * известный сдвиг. Это уже не измерение, а его продолжение, и оно ближе к
 * правде, чем ноль: русское издание кончается позже английского, и к нулю
 * расхождение не возвращается.
 */
const TAIL_SHIFT = PAGE_MAP[CATALOGUE_LAST] - CATALOGUE_LAST;

/**
 * Страница русской книги по номеру из английской.
 *
 * Всё, что до каталога, возвращается как есть: там издания совпадают
 * постранично, это проверено по страницам 150, 163, 164, 177, 187, 188, 190
 * и 191. Мусор на входе тоже возвращается нетронутым — открыть книгу не на той
 * странице лучше, чем не открыть вовсе.
 *
 * @param {Number|String} page - номер страницы по английскому изданию
 * @returns {Number|String} - номер страницы русского издания
 */
export function bookPage(page) {
  const number = Number(page);
  if (!Number.isFinite(number) || number <= 0) return page;
  if (number < CATALOGUE_FIRST) return number;

  const known = PAGE_MAP[number];
  if (known !== undefined) return known;

  return Math.min(number + TAIL_SHIFT, LAST_PAGE);
}
