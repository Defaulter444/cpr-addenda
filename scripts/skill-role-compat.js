const STATE = Symbol.for("cpr-addenda.skillRoleCompatibility");
const ATTACK = Symbol("skillRoleAttack");
const bySource = new Map(CORE_SKILLS.map(entry => [entry.source, entry]));
const byName = new Map(CORE_SKILLS.flatMap(entry => [[entry.name, entry], [entry.ru, entry]]));
export function canonicalSkillRoleName(name) {
  return typeof name === "string" ? (RUSSIAN_ALIASES[name] ?? name) : name;
}
function sourceOf(item) {
  return item?._stats?.compendiumSource || item?.flags?.core?.sourceId ||
    (item?.pack ? `Compendium.${item.pack}.Item.${item.id}` : "");
}
export function resolveCoreSkill(actor, name) {
  if (typeof name !== "string") return undefined;
  const skills = actor?.itemTypes?.skill ?? [];
  const exact = skills.find(item => item.name === name);
  if (exact) return exact;
  if (name === "Martial Arts" || name === "Боевые искусства") {
    // Core's generic unarmed weapon represents an ordinary Martial Arts attack.
    // RTG FAQ: use the highest learned form, never add the forms together.
    return skills.filter(item => item.system.skillType === "martialArt" && Number(item.system.level) > 0)
      .sort((a, b) => Number(b.system.level) - Number(a.system.level) || canonicalSkillRoleName(a.name).localeCompare(canonicalSkillRoleName(b.name)))[0];
  }
  const canonical = canonicalSkillRoleName(name);
  if (!byName.has(name) && !byName.has(canonical)) return undefined;
  const matches = skills.filter(item => canonicalSkillRoleName(item.name) === canonical);
  return matches.length === 1 ? matches[0] : undefined;
}

/** Actual core attack constructors are synchronous and search EmbeddedCollection.find.
 * Try an alias only when the original predicate finds no document. The result is
 * always the real skill, with its real name/level; no stored name or reference changes. */
function withAttackAliases(actor, callback) {
  const items = actor?.items;
  if (!items || typeof items.find !== "function") return callback();
  const descriptor = Object.getOwnPropertyDescriptor(items, "find");
  const find = items.find;
  Object.defineProperty(items, "find", { configurable: true, writable: true, value(predicate, ...args) {
    const direct = find.call(this, predicate, ...args);
    if (direct !== undefined) return direct;
    const candidates = [];
    const martial = resolveCoreSkill(actor, "Martial Arts");
    for (const item of this) {
      if (item.type !== "skill") continue;
      const known = byName.get(item.name) ?? (item === martial ? { name: item.name, ru: item.name } : null);
      if (!known) continue;
      for (const name of new Set([known.name, known.ru, ...(item === martial ? ["Martial Arts", "Боевые искусства"] : [])])) {
        if (name === item.name) continue;
        const alias = new Proxy(item, { get(target, property) {
          return property === "name" ? name : Reflect.get(target, property, target);
        } });
        if (predicate(alias)) { candidates.push(item); break; }
      }
    }
    return candidates.length === 1 ? candidates[0] : undefined;
  } });
  try { return callback(); }
  finally {
    if (descriptor) Object.defineProperty(items, "find", descriptor);
    else delete items.find;
  }
}

export function applySkillRoleItemCompatibility(item) {
  if (game.system.id !== "cyberpunk-red-core") return;
  if (item.type === "skill" && item.system.skillType === "generic") {
    // The migration missed names containing spaces. Source identity is preferred;
    // exact core names also cover the system's new-character copies without flags.
    const known = bySource.get(sourceOf(item)) ?? byName.get(item.name);
    if (known && known.kind !== "generic") item.system.skillType = known.kind;
  }
  if (typeof item._createAttackRoll !== "function" || item._createAttackRoll[ATTACK]) return;
  const attack = item._createAttackRoll;
  const compatible = function (type, actor, ...args) {
    const required = ['autofire', 'suppressive'].includes(type) ? 'Autofire' : this.system.weaponSkill;
    if (!resolveCoreSkill(actor, required)) {
      ui.notifications.warn(required === 'Martial Arts' || required === 'Боевые искусства'
        ? 'Для атаки боевыми искусствами сначала добавьте персонажу изученный стиль с уровнем выше 0.'
        : `У персонажа отсутствует навык оружия: ${required || 'не указан'}. Проверьте настройку предмета.`);
      return null;
    }
    return withAttackAliases(actor, () => attack.call(this, type, actor, ...args));
  };
  compatible[ATTACK] = true;
  item._createAttackRoll = compatible;
}

export function registerSkillRoleCompatibility(filterModifiers = result => result) {
  if (game.system.id !== "cyberpunk-red-core") return false;
  if (globalThis[STATE]) return true;
  globalThis.cprAddendaSkillRoleCore = { SystemUtils, CPRRoleItem, CPRMod };
  const originalSlug = SystemUtils.slugify.bind(SystemUtils);
  const effectAliases = new Map();
  for (const [translated, original] of Object.entries(RUSSIAN_ALIASES)) {
    for (const suffix of ["", "Hearing", "Sight"]) {
      effectAliases.set(`bonuses.${originalSlug(translated)}${suffix}`, `bonuses.${originalSlug(original)}${suffix}`);
    }
  }
  // Core's effect picker omits parentheses in these two keys, while the
  // role names (and their localization keys) retain them. Normalize only the
  // modifier lookup; saved effect changes and translated ability names stay intact.
  effectAliases.set("bonuses.medicalTechCryosystemOperation", "bonuses.medicalTech(CryosystemOperation)");
  effectAliases.set("bonuses.medicalTechPharmaceuticals", "bonuses.medicalTech(Pharmaceuticals)");
  const keyOf = key => effectAliases.get(key) ?? key;
  const register = (target, fn) => libWrapper.register("cpr-addenda", target, fn, "WRAPPER");
  register("cprAddendaSkillRoleCore.SystemUtils.slugify", function (wrapped, name, ...args) {
    return wrapped(canonicalSkillRoleName(name), ...args);
  });
  register("CONFIG.Actor.documentClass.prototype.getSkillLevel", function (wrapped, name, ...args) {
    return wrapped(resolveCoreSkill(this, name)?.name ?? name, ...args);
  });
  register("cprAddendaSkillRoleCore.CPRRoleItem.prototype.getRoleMods", function (wrapped, name, universal = false) {
    if (universal) return wrapped(name, universal);
    const abilities = [this.system, ...this.system.abilities];
    const saved = abilities.map(ability => ability.bonuses);
    abilities.forEach(ability => { ability.bonuses = ability.bonuses.map(bonus => typeof bonus === "string"
      ? canonicalSkillRoleName(bonus) : { ...bonus, name: canonicalSkillRoleName(bonus.name) }); });
    try { return wrapped(canonicalSkillRoleName(name), universal); }
    finally { abilities.forEach((ability, index) => { ability.bonuses = saved[index]; }); }
  });
  register("cprAddendaSkillRoleCore.CPRRoleItem.prototype._createRoleRoll", function (wrapped, type, actor, info) {
    const sub = info.rollSubType === "subRoleAbility";
    const ability = sub ? this.system.abilities.find(value =>
      value.name === info.subRoleName || canonicalSkillRoleName(value.name) === canonicalSkillRoleName(info.subRoleName)) : this.system;
    if (!ability) return wrapped(type, actor, info);
    const original = ability.skill;
    const name = typeof original === "string" ? original : original?.name;
    const skill = resolveCoreSkill(actor, name);
    if (skill) ability.skill = sub ? { ...(typeof original === "object" ? original : {}), name: skill.name } : skill.name;
    try { return wrapped(type, actor, sub ? { ...info, subRoleName: ability.name } : info); }
    finally { ability.skill = original; }
  });
  register("cprAddendaSkillRoleCore.CPRMod.getAllModifiers", function (wrapped, effects, disabled = false) {
    effects = Array.from(effects);
    const result = wrapped(effects, disabled).map(mod => {
      const key = keyOf(mod.key);
      // Preserve CPRMod's prototype, ID, flags and numeric behavior.
      if (key !== mod.key) mod.key = key;
      return mod;
    });
    return filterModifiers(result, effects, disabled);
  });
  register("CONFIG.ActiveEffect.documentClass.prototype.apply", function (wrapped, actor, change, ...args) {
    const key = keyOf(change.key);
    return wrapped(actor, key === change.key ? change : { ...change, key }, ...args);
  });
  globalThis[STATE] = true;
  return true;
}
