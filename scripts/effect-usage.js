/**
 * Режим «пока установлено» для активных эффектов модификаций.
 *
 * Что даёт система из коробки. Активный эффект в Foundry умеет менять только
 * своего носителя или актёра, которому носитель принадлежит. Изменить предмет,
 * в который вставлена модификация, эффект не может — это прямо оговорено в коде
 * системы (`cpr-attackable.js`, комментарий к `_getAttackMod`). Поэтому правки
 * характеристик ствола идут через `system.modifiers`, а эффекты — только на
 * персонажа.
 *
 * Чего не хватает. У предметов есть поле `system.usage`, среди значений которого
 * есть `installed` — «эффект работает, только пока предмет установлен». Система
 * умеет его обрабатывать (`cpr-effects.js`, `areEffectsSuppressed`), но в
 * выпадающем списке на листе предмета предлагает его исключительно для
 * киберware (`getAllowedUsage`). Для модификаций режим недоступен, хотя данные
 * его полностью поддерживают.
 *
 * Что делает модуль. Возвращает `installed` в список доступных режимов для
 * модификаций. Благодаря этому глушитель может давать персонажу эффект, который
 * живёт ровно столько, сколько глушитель навинчен на ствол, — и гаснет, стоит
 * его снять.
 */

import { MODULE_ID, SETTINGS } from "./constants.js";

/**
 * Добавляет режим `installed` в список разрешённых режимов модификации.
 *
 * Вызывается из обёртки над `loadMixins`, потому что система пересчитывает
 * `system.allowedUsage` внутри неё и затирает любые более ранние правки.
 *
 * @param {Item} item - предмет, которому только что загрузили миксины
 */
export function applyInstalledUsage(item) {
  if (!game.settings.get(MODULE_ID, SETTINGS.installedUsage)) return;
  if (item.type !== "itemUpgrade") return;

  const usage = item.system?.allowedUsage;
  if (!Array.isArray(usage)) return;
  if (usage.includes("installed")) return;

  usage.push("installed");
}
